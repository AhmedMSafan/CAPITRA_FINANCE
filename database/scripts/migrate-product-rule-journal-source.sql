           SET "BPMN_XML" = replace("BPMN_XML", 'finova:eventCode="' || x.ev || '"', 'finova:ruleCode="' || x.rule || '"')
         WHERE "BPMN_XML" LIKE '%finova:eventCode="' || x.ev || '"%';
