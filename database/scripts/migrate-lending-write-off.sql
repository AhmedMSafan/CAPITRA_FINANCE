        "REQUESTED_BY" character varying(100) NOT NULL,
        "REQUESTED_AT" timestamp with time zone NOT NULL,
        "DECIDED_BY" character varying(100),
        "DECIDED_AT" timestamp with time zone,
        "DECISION_NOTES" character varying(1000),
        "WRITE_OFF_DATE" date,
        "GL_TRAN_SET_ID" character varying(40),
        "CREATED_AT" timestamp with time zone NOT NULL,
        "CREATED_BY" character varying(100) NOT NULL,
        "UPDATED_AT" timestamp with time zone,
        "UPDATED_BY" character varying(100),
        "ROW_VERSION" integer NOT NULL,
        CONSTRAINT "PK_LND_WRITE_OFFS" PRIMARY KEY ("WRITE_OFF_ID"),
        CONSTRAINT "FK_LND_WRITE_OFFS_LND_LOANS" FOREIGN KEY ("LOAN_ID") REFERENCES "LND_LOANS" ("LOAN_ID") ON DELETE RESTRICT
