-- =====================================================================
-- Capitra: Workflow versions (EF migration 20261108212222_WorkflowVersions). Safe to run more than once.
--   New table WFE_DEFINITION_VERSIONS keeps each released version of a workflow.
--   WFE_WORKFLOW_INSTANCES gets DEFINITION_VERSION_ID: the version an instance runs on.
--   Every workflow as it is today becomes version 1 (or the number it already showed),
--   and every existing instance is set to run on it. Nothing else changes.
-- Run in pgAdmin > Query Tool on CAPITRA_DB (F5).
-- =====================================================================
START TRANSACTION;

DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "SYS_EF_MIGRATION_HISTORY" WHERE "MigrationId" = '20261108212222_WorkflowVersions') THEN
    ALTER TABLE "WFE_WORKFLOW_INSTANCES" ADD "DEFINITION_VERSION_ID" bigint;
    END IF;
END $EF$;

DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "SYS_EF_MIGRATION_HISTORY" WHERE "MigrationId" = '20261108212222_WorkflowVersions') THEN
    CREATE TABLE "WFE_DEFINITION_VERSIONS" (
        "DEFINITION_VERSION_ID" bigint GENERATED BY DEFAULT AS IDENTITY,
        "WORKFLOW_DEFINITION_ID" bigint NOT NULL,
        "VERSION_NO" integer NOT NULL,
        "BPMN_XML" text NOT NULL,
        "RELEASED_AT" timestamp with time zone NOT NULL,
        "RELEASED_BY" character varying(100) NOT NULL,
        "CREATED_BY" character varying(100) NOT NULL,
        "CREATED_AT" timestamp with time zone NOT NULL,
        "UPDATED_BY" character varying(100),
        "UPDATED_AT" timestamp with time zone,
        "ROW_VERSION" integer NOT NULL,
        CONSTRAINT "PK_WFE_DEFINITION_VERSIONS" PRIMARY KEY ("DEFINITION_VERSION_ID"),
        CONSTRAINT "FK_WFE_DEFINITION_VERSIONS_WFE_WORKFLOW_DEFINITIONS" FOREIGN KEY ("WORKFLOW_DEFINITION_ID") REFERENCES "WFE_WORKFLOW_DEFINITIONS" ("WORKFLOW_DEFINITION_ID") ON DELETE CASCADE
    );
    END IF;
END $EF$;

DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "SYS_EF_MIGRATION_HISTORY" WHERE "MigrationId" = '20261108212222_WorkflowVersions') THEN
    CREATE INDEX "IX_WFE_WORKFLOW_INSTANCES_DEFINITION_VERSION_ID" ON "WFE_WORKFLOW_INSTANCES" ("DEFINITION_VERSION_ID");
    END IF;
END $EF$;

DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "SYS_EF_MIGRATION_HISTORY" WHERE "MigrationId" = '20261108212222_WorkflowVersions') THEN
    CREATE UNIQUE INDEX "UQ_WFE_DEFINITION_VERSIONS_WORKFLOW_DEFINITION_ID_VERSION_NO" ON "WFE_DEFINITION_VERSIONS" ("WORKFLOW_DEFINITION_ID", "VERSION_NO");
    END IF;
END $EF$;

DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "SYS_EF_MIGRATION_HISTORY" WHERE "MigrationId" = '20261108212222_WorkflowVersions') THEN
    INSERT INTO "WFE_DEFINITION_VERSIONS" ("WORKFLOW_DEFINITION_ID", "VERSION_NO", "BPMN_XML", "RELEASED_AT", "RELEASED_BY",
        "CREATED_BY", "CREATED_AT", "ROW_VERSION")
    SELECT d."WORKFLOW_DEFINITION_ID",
           CASE WHEN d."VERSION_NO" ~ '^[0-9]{1,6}$' AND d."VERSION_NO"::int > 0 THEN d."VERSION_NO"::int ELSE 1 END,
           d."BPMN_XML", COALESCE(d."UPDATED_AT", d."CREATED_AT"), COALESCE(d."UPDATED_BY", d."CREATED_BY"),
           'SYSTEM', now(), 1
    FROM "WFE_WORKFLOW_DEFINITIONS" d
    WHERE NOT EXISTS (SELECT 1 FROM "WFE_DEFINITION_VERSIONS" v WHERE v."WORKFLOW_DEFINITION_ID" = d."WORKFLOW_DEFINITION_ID");
    UPDATE "WFE_WORKFLOW_DEFINITIONS" d
    SET "VERSION_NO" = v."VERSION_NO"::text
    FROM "WFE_DEFINITION_VERSIONS" v WHERE v."WORKFLOW_DEFINITION_ID" = d."WORKFLOW_DEFINITION_ID";
    UPDATE "WFE_WORKFLOW_INSTANCES" i
    SET "DEFINITION_VERSION_ID" = v."DEFINITION_VERSION_ID"
    FROM "WFE_DEFINITION_VERSIONS" v
    WHERE v."WORKFLOW_DEFINITION_ID" = i."WORKFLOW_DEFINITION_ID" AND i."DEFINITION_VERSION_ID" IS NULL;
    END IF;
END $EF$;

DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "SYS_EF_MIGRATION_HISTORY" WHERE "MigrationId" = '20261108212222_WorkflowVersions') THEN
    ALTER TABLE "WFE_WORKFLOW_INSTANCES" ADD CONSTRAINT "FK_WFE_WORKFLOW_INSTANCES_WFE_DEFINITION_VERSIONS" FOREIGN KEY ("DEFINITION_VERSION_ID") REFERENCES "WFE_DEFINITION_VERSIONS" ("DEFINITION_VERSION_ID") ON DELETE RESTRICT;
    END IF;
END $EF$;

DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "SYS_EF_MIGRATION_HISTORY" WHERE "MigrationId" = '20261108212222_WorkflowVersions') THEN
    INSERT INTO "SYS_EF_MIGRATION_HISTORY" ("MigrationId", "ProductVersion")
    VALUES ('20261108212222_WorkflowVersions', '10.0.13');
    END IF;
END $EF$;
COMMIT;

