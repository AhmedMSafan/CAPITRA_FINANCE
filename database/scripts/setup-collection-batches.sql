-- =====================================================================================================================
-- Capitra: collection batches (agreed with Ahmed, 1 Nov 2026).
-- Run in pgAdmin > Query Tool on CAPITRA_DB. Press F5. Safe to run again: what exists is kept.
--
-- Adds FCT_COLLECTION_BATCHES and FCT_COLLECTION_BATCH_LINES (migration CollectionBatches).
-- From then on every Apply Bank Results on the Cheques Collection page makes one collection batch COL-yyyyMMdd-nnnnnn with its
-- cheques, and posts ONE GL Tran Set for the whole batch: DR each deposit bank's GL account / CR 230104 customer liability.
-- The GL Tran Set ID is kept on the batch and on each repayment. See Collection and Repayments > Collection Batches.
-- =====================================================================================================================

START TRANSACTION;

DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "SYS_EF_MIGRATION_HISTORY" WHERE "MigrationId" = '20261101230749_CollectionBatches') THEN
    CREATE TABLE "FCT_COLLECTION_BATCHES" (
        "COLLECTION_BATCH_ID" bigint GENERATED BY DEFAULT AS IDENTITY,
        "BATCH_NO" character varying(30) NOT NULL,
        "BATCH_DATE" date NOT NULL,
        "COLLECTED_COUNT" integer NOT NULL,
        "COLLECTED_AMOUNT" numeric(18,2) NOT NULL,
        "BOUNCED_COUNT" integer NOT NULL,
        "BOUNCED_AMOUNT" numeric(18,2) NOT NULL,
        "REJECTED_COUNT" integer NOT NULL,
        "REJECTED_AMOUNT" numeric(18,2) NOT NULL,
        "REPAYMENTS_COUNT" integer NOT NULL,
        "GL_TRAN_SET_ID" character varying(40),
        "NOTES" character varying(2000),
        "CREATED_BY" character varying(100) NOT NULL,
        "CREATED_AT" timestamp with time zone NOT NULL,
        "UPDATED_BY" character varying(100),
        "UPDATED_AT" timestamp with time zone,
        "ROW_VERSION" integer NOT NULL,
        CONSTRAINT "PK_FCT_COLLECTION_BATCHES" PRIMARY KEY ("COLLECTION_BATCH_ID")
    );
    END IF;
END $EF$;

DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "SYS_EF_MIGRATION_HISTORY" WHERE "MigrationId" = '20261101230749_CollectionBatches') THEN
    CREATE TABLE "FCT_COLLECTION_BATCH_LINES" (
        "COLLECTION_BATCH_LINE_ID" bigint GENERATED BY DEFAULT AS IDENTITY,
        "COLLECTION_BATCH_ID" bigint NOT NULL,
        "LINE_NO" integer NOT NULL,
        "CHEQUE_ID" bigint NOT NULL,
        "CHEQUE_REF" character varying(50),
        "CHEQUE_NO" character varying(100) NOT NULL,
        "DUE_DATE" date NOT NULL,
        "CUSTOMER_ID" character varying(100),
        "DEPOSIT_BANK_ACCOUNT_ID" bigint,
        "CHEQUE_AMOUNT" numeric(18,2) NOT NULL,
        "CURRENCY_CODE" character varying(3),
        "RESULT_CODE" character varying(20) NOT NULL,
        "STATUS_DATE" date NOT NULL,
        "BANK_STATEMENT_REFERENCE" character varying(100),
        "REASON_CODE" character varying(50),
        "NOTES" character varying(2000),
        "REPAYMENT_TXN_ID" bigint,
        "CREATED_BY" character varying(100) NOT NULL,
        "CREATED_AT" timestamp with time zone NOT NULL,
        "UPDATED_BY" character varying(100),
        "UPDATED_AT" timestamp with time zone,
        "ROW_VERSION" integer NOT NULL,
        CONSTRAINT "PK_FCT_COLLECTION_BATCH_LINES" PRIMARY KEY ("COLLECTION_BATCH_LINE_ID"),
        CONSTRAINT "FK_FCT_COLLECTION_BATCH_LINES_FCT_COLLECTION_BATCHES" FOREIGN KEY ("COLLECTION_BATCH_ID") REFERENCES "FCT_COLLECTION_BATCHES" ("COLLECTION_BATCH_ID") ON DELETE CASCADE,
        CONSTRAINT "FK_FCT_COLLECTION_BATCH_LINES_FCT_REPAYMENT_TRANSACTIONS" FOREIGN KEY ("REPAYMENT_TXN_ID") REFERENCES "FCT_REPAYMENT_TRANSACTIONS" ("REPAYMENT_TXN_ID") ON DELETE RESTRICT
    );
    END IF;
END $EF$;

DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "SYS_EF_MIGRATION_HISTORY" WHERE "MigrationId" = '20261101230749_CollectionBatches') THEN
    CREATE INDEX "IX_FCT_COLLECTION_BATCH_LINES_CHEQUE_ID" ON "FCT_COLLECTION_BATCH_LINES" ("CHEQUE_ID");
    END IF;
END $EF$;

DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "SYS_EF_MIGRATION_HISTORY" WHERE "MigrationId" = '20261101230749_CollectionBatches') THEN
    CREATE INDEX "IX_FCT_COLLECTION_BATCH_LINES_REPAYMENT_TXN_ID" ON "FCT_COLLECTION_BATCH_LINES" ("REPAYMENT_TXN_ID");
    END IF;
END $EF$;

DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "SYS_EF_MIGRATION_HISTORY" WHERE "MigrationId" = '20261101230749_CollectionBatches') THEN
    CREATE UNIQUE INDEX "UQ_FCT_COLLECTION_BATCH_LINES_COLLECTION_BATCH_ID_LINE_NO" ON "FCT_COLLECTION_BATCH_LINES" ("COLLECTION_BATCH_ID", "LINE_NO");
    END IF;
END $EF$;

DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "SYS_EF_MIGRATION_HISTORY" WHERE "MigrationId" = '20261101230749_CollectionBatches') THEN
    CREATE INDEX "IX_FCT_COLLECTION_BATCHES_GL_TRAN_SET_ID" ON "FCT_COLLECTION_BATCHES" ("GL_TRAN_SET_ID");
    END IF;
END $EF$;

DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "SYS_EF_MIGRATION_HISTORY" WHERE "MigrationId" = '20261101230749_CollectionBatches') THEN
    CREATE UNIQUE INDEX "UQ_FCT_COLLECTION_BATCHES_BATCH_NO" ON "FCT_COLLECTION_BATCHES" ("BATCH_NO");
    END IF;
END $EF$;

DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "SYS_EF_MIGRATION_HISTORY" WHERE "MigrationId" = '20261101230749_CollectionBatches') THEN
    INSERT INTO "SYS_EF_MIGRATION_HISTORY" ("MigrationId", "ProductVersion")
    VALUES ('20261101230749_CollectionBatches', '10.0.13');
    END IF;
END $EF$;
COMMIT;

