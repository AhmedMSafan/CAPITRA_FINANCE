select count(*) TOTAL_PORTFOLIOS, sum(FACE_VALUE) TOTAL_FACE_VALUE, sum(PROPOSED_PURCHASE_VALUE) TOTAL_PURCHASE_VALUE,
       sum(OUTSTANDING_VALUE) TOTAL_OUTSTANDING_VALUE, sum(EXPECTED_RETURN_AMOUNT) TOTAL_EXPECTED_RETURN,
       avg(PROPOSED_PURCHASE_VALUE) AVG_PORTFOLIO_SIZE,
       sum(case when PORTFOLIO_STATUS_CODE='APPROVED' then 1 else 0 end) APPROVED_COUNT,
       sum(case when PORTFOLIO_STATUS_CODE='REJECTED' then 1 else 0 end) REJECTED_COUNT,
       sum(case when PORTFOLIO_STATUS_CODE not in ('APPROVED','REJECTED','CLOSED') then PROPOSED_PURCHASE_VALUE else 0 end) PIPELINE_VALUE
from FNV_PURSHASED_PORTFOLIO;
