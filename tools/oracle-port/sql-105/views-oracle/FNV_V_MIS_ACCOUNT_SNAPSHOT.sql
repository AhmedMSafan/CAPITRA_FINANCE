select s.SNAPSHOT_ID, s.AS_OF_DATE, s.PORTFOLIO_ACCOUNT_ID, p.PORTFOLIO_ID, p.PORTFOLIO_NO, i.INVESTOR_CODE,
       nvl(i.FULL_NAME_EN,i.FULL_NAME_AR) INVESTOR_NAME, u.UNIT_CODE, s.OUTSTANDING_VALUE, s.ARREARS_AMOUNT,
       s.NEXT_DUE_DATE, s.PAYMENT_STATUS, s.CREATED_ON
from FNV_ACCOUNT_SNAPSHOT s
join FNV_PURSHASED_PORTFOLIO_ACCOUNT a on a.PORTFOLIO_ACCOUNT_ID = s.PORTFOLIO_ACCOUNT_ID
join FNV_PURSHASED_PORTFOLIO p on p.PORTFOLIO_ID = a.PORTFOLIO_ID
join FNV_INVESTOR i on i.INVESTOR_ID = a.INVESTOR_ID
join FNV_PROJECT_UNIT u on u.UNIT_ID = a.UNIT_ID;
