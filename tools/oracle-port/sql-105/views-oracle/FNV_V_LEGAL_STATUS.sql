select p.PORTFOLIO_ID, p.PORTFOLIO_NO, lr.LEGAL_REVIEW_ID, lr.OWNERSHIP_VERIFIED_FLAG, lr.BUILDING_LICENSE_VERIFIED_FLAG,
       lr.REGISTRATION_POSSIBLE_FLAG, lr.MORTGAGE_POSSIBLE_FLAG, lr.ENCUMBRANCE_FREE_FLAG, lr.TITLE_DEED_VERIFIED_FLAG,
       case when lr.LEGAL_REVIEW_ID is not null and lr.OWNERSHIP_VERIFIED_FLAG='Y' and lr.BUILDING_LICENSE_VERIFIED_FLAG='Y'
             and lr.REGISTRATION_POSSIBLE_FLAG='Y' and lr.MORTGAGE_POSSIBLE_FLAG='Y' and lr.ENCUMBRANCE_FREE_FLAG='Y'
             and lr.TITLE_DEED_VERIFIED_FLAG='Y' then 'Y' else 'N' end LEGAL_READY_FLAG
from FNV_PURSHASED_PORTFOLIO p left join FNV_LEGAL_REVIEW lr on lr.PORTFOLIO_ID=p.PORTFOLIO_ID;
