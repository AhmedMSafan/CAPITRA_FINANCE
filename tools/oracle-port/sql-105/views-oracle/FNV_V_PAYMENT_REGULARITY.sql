select pa.PORTFOLIO_ACCOUNT_ID, pa.PORTFOLIO_ID, pa.INVESTOR_ID, i.INVESTOR_CODE, i.FULL_NAME_AR, i.FULL_NAME_EN,
       count(ap.PAYMENT_ID) as PAYMENT_COUNT,
       sum(case when ap.PAYMENT_STATUS_CODE='PAID' then 1 else 0 end) as PAID_COUNT,
       sum(case when ap.PAYMENT_STATUS_CODE='LATE' then 1 else 0 end) as LATE_COUNT,
       sum(case when ap.PAYMENT_STATUS_CODE in ('PARTIAL','UNPAID') then 1 else 0 end) as PROBLEM_COUNT,
       max(ap.DAYS_LATE) as MAX_DAYS_LATE, sum(ap.DUE_AMOUNT) as TOTAL_DUE, sum(ap.PAID_AMOUNT) as TOTAL_PAID
from FNV_PURSHASED_PORTFOLIO_ACCOUNT pa
join FNV_INVESTOR i on i.INVESTOR_ID=pa.INVESTOR_ID
left join FNV_ACCOUNT_PAYMENT ap on ap.PORTFOLIO_ACCOUNT_ID=pa.PORTFOLIO_ACCOUNT_ID
group by pa.PORTFOLIO_ACCOUNT_ID, pa.PORTFOLIO_ID, pa.INVESTOR_ID, i.INVESTOR_CODE, i.FULL_NAME_AR, i.FULL_NAME_EN;
