with req as (select count(*) REQUIRED_COUNT from REF_GUARANTEE_TYPE where MANDATORY_FLAG='Y' and ACTIVE_FLAG='Y'),
got as (select PORTFOLIO_ID, count(distinct GUARANTEE_TYPE_CODE) VERIFIED_REQUIRED_COUNT
        from FNV_GUARANTEE g
        where VERIFIED_FLAG='Y'
          and exists (select 1 from REF_GUARANTEE_TYPE r where r.GUARANTEE_TYPE_CODE=g.GUARANTEE_TYPE_CODE and r.MANDATORY_FLAG='Y' and r.ACTIVE_FLAG='Y')
        group by PORTFOLIO_ID)
select p.PORTFOLIO_ID, p.PORTFOLIO_NO, r.REQUIRED_COUNT, nvl(g.VERIFIED_REQUIRED_COUNT,0) VERIFIED_REQUIRED_COUNT,
       greatest(r.REQUIRED_COUNT-nvl(g.VERIFIED_REQUIRED_COUNT,0),0) MISSING_REQUIRED_COUNT,
       case when nvl(g.VERIFIED_REQUIRED_COUNT,0) >= r.REQUIRED_COUNT then 'Y' else 'N' end GUARANTEE_READY_FLAG
from FNV_PURSHASED_PORTFOLIO p cross join req r left join got g on g.PORTFOLIO_ID=p.PORTFOLIO_ID;
