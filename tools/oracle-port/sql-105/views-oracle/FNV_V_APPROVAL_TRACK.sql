select a.APPROVAL_ID, a.PORTFOLIO_ID, p.PORTFOLIO_NO, a.STEP_CODE, s.STEP_NAME_AR, s.STEP_NAME_EN, a.SEQUENCE_NO,
       a.ASSIGNED_TO, a.ASSIGNED_DATE, a.DECISION_CODE, d.DECISION_NAME_AR, d.DECISION_NAME_EN, a.DECISION_DATE, a.RETURN_TO_STEP_CODE
from FNV_PURSHASED_PORTFOLIO_APPROVAL a
join FNV_PURSHASED_PORTFOLIO p on p.PORTFOLIO_ID=a.PORTFOLIO_ID
join REF_APPROVAL_STEP s on s.STEP_CODE=a.STEP_CODE
left join REF_DECISION_TYPE d on d.DECISION_CODE=a.DECISION_CODE;
