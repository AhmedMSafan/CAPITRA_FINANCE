select pf.PORTFOLIO_ID, pf.PORTFOLIO_NO, pf.OUTSTANDING_VALUE, pf.EXPECTED_RETURN_AMOUNT,
       pf.OUTSTANDING_VALUE + pf.EXPECTED_RETURN_AMOUNT as REQUIRED_COVERAGE_AMOUNT,
       nvl(sum(c.CHEQUE_AMOUNT),0) as CHEQUE_TOTAL_AMOUNT,
       case when (pf.OUTSTANDING_VALUE + pf.EXPECTED_RETURN_AMOUNT)=0 then null
            else round(nvl(sum(c.CHEQUE_AMOUNT),0) / (pf.OUTSTANDING_VALUE + pf.EXPECTED_RETURN_AMOUNT) * 100, 2) end as CHEQUE_COVERAGE_PCT,
       case when nvl(sum(c.CHEQUE_AMOUNT),0) >= (pf.OUTSTANDING_VALUE + pf.EXPECTED_RETURN_AMOUNT) then 'Y' else 'N' end as COVERAGE_OK_FLAG
from FNV_PURSHASED_PORTFOLIO pf
left join FNV_PURCHASED_PORTFOLIO_CHEQUE c on c.PORTFOLIO_ID=pf.PORTFOLIO_ID
group by pf.PORTFOLIO_ID, pf.PORTFOLIO_NO, pf.OUTSTANDING_VALUE, pf.EXPECTED_RETURN_AMOUNT;
