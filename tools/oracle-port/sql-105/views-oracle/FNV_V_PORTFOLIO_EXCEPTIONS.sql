select p.PORTFOLIO_ID, p.PORTFOLIO_NO, 'DUE_DILIGENCE' EXCEPTION_TYPE, dd.CHECK_TYPE_CODE EXCEPTION_CODE, dd.FINDINGS EXCEPTION_DETAILS
from FNV_PURSHASED_PORTFOLIO p join FNV_DUE_DILIGENCE dd on dd.PORTFOLIO_ID=p.PORTFOLIO_ID where dd.EXCEPTION_FLAG='Y'
union all
select p.PORTFOLIO_ID, p.PORTFOLIO_NO, 'PAYMENT_HISTORY', 'PAYMENT_IRREGULARITY', to_clob('Payment problems found for investor '||pr.FULL_NAME_EN)
from FNV_PURSHASED_PORTFOLIO p join FNV_V_PAYMENT_REGULARITY pr on pr.PORTFOLIO_ID=p.PORTFOLIO_ID
where pr.PAYMENT_COUNT < 12 or pr.PROBLEM_COUNT > 0
union all
select p.PORTFOLIO_ID, p.PORTFOLIO_NO, 'CHEQUE_COVERAGE', 'INSUFFICIENT_COVERAGE', to_clob('Cheque coverage is below required amount')
from FNV_PURSHASED_PORTFOLIO p join FNV_V_CHEQUE_COVERAGE cc on cc.PORTFOLIO_ID=p.PORTFOLIO_ID where cc.COVERAGE_OK_FLAG='N';
