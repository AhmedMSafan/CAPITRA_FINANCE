with req as (select count(*) REQUIRED_COUNT from REF_DOCUMENT_TYPE where IS_MANDATORY='Y' and IS_ACTIVE='Y'),
doc as (select PORTFOLIO_ID, count(distinct DOCUMENT_TYPE_CODE) RECEIVED_REQUIRED_COUNT
        from FNV_PURSHASED_PORTFOLIO_DOCUMENT d
        where exists (select 1 from REF_DOCUMENT_TYPE r where r.DOCUMENT_TYPE_CODE=d.DOCUMENT_TYPE_CODE and r.IS_MANDATORY='Y' and r.IS_ACTIVE='Y')
        group by PORTFOLIO_ID)
select p.PORTFOLIO_ID, p.PORTFOLIO_NO, r.REQUIRED_COUNT, nvl(d.RECEIVED_REQUIRED_COUNT,0) RECEIVED_REQUIRED_COUNT,
       greatest(r.REQUIRED_COUNT-nvl(d.RECEIVED_REQUIRED_COUNT,0),0) MISSING_REQUIRED_COUNT,
       case when r.REQUIRED_COUNT=0 then 100 else round(nvl(d.RECEIVED_REQUIRED_COUNT,0)/r.REQUIRED_COUNT*100,2) end DOCUMENT_COMPLETION_PCT,
       case when nvl(d.RECEIVED_REQUIRED_COUNT,0) >= r.REQUIRED_COUNT then 'Y' else 'N' end DOCUMENT_READY_FLAG
from FNV_PURSHASED_PORTFOLIO p cross join req r left join doc d on d.PORTFOLIO_ID=p.PORTFOLIO_ID;
