select PORTFOLIO_STATUS_CODE, count(*) CASE_COUNT, sum(PROPOSED_PURCHASE_VALUE) PIPELINE_VALUE,
       round(avg(trunc(sysdate)-trunc(REQUEST_DATE)),1) AVG_DAYS, max(trunc(sysdate)-trunc(REQUEST_DATE)) OLDEST_DAYS
from FNV_PURSHASED_PORTFOLIO where PORTFOLIO_STATUS_CODE not in ('CLOSED') group by PORTFOLIO_STATUS_CODE;
