select s.*,
       r.DOCUMENT_READY_FLAG, r.DD_READY_FLAG, r.VALUATION_READY_FLAG, r.LEGAL_READY_FLAG, r.FINANCE_READY_FLAG,
       r.CHEQUE_READY_FLAG, r.GUARANTEE_READY_FLAG, r.PAYMENT_HISTORY_READY_FLAG, r.READY_FOR_SUBMISSION_FLAG,
       trunc(sysdate)-trunc(s.REQUEST_DATE) as AGE_DAYS
from FNV_V_PORTFOLIO_SUMMARY s
left join FNV_V_PORTFOLIO_READINESS r on r.PORTFOLIO_ID=s.PORTFOLIO_ID
