select d.DEVELOPER_ID, d.DEVELOPER_CODE, d.LEGAL_NAME_AR, d.LEGAL_NAME_EN,
       count(distinct pf.PORTFOLIO_ID) PORTFOLIO_COUNT, count(distinct pf.PROJECT_ID) PROJECT_COUNT,
       count(distinct pa.INVESTOR_ID) INVESTOR_COUNT, sum(pf.FACE_VALUE) FACE_VALUE,
       sum(pf.PROPOSED_PURCHASE_VALUE) PURCHASE_VALUE, sum(pf.OUTSTANDING_VALUE) OUTSTANDING_EXPOSURE
from FNV_REALESTATE_DEVELOPER d
left join FNV_PURSHASED_PORTFOLIO pf on pf.DEVELOPER_ID=d.DEVELOPER_ID
left join FNV_PURSHASED_PORTFOLIO_ACCOUNT pa on pa.PORTFOLIO_ID=pf.PORTFOLIO_ID
group by d.DEVELOPER_ID, d.DEVELOPER_CODE, d.LEGAL_NAME_AR, d.LEGAL_NAME_EN;
