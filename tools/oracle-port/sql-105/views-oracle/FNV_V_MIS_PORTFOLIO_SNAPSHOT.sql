select s.SNAPSHOT_ID, s.AS_OF_DATE, s.PORTFOLIO_ID, p.PORTFOLIO_NO, d.DEVELOPER_CODE, nvl(d.LEGAL_NAME_EN,d.LEGAL_NAME_AR) DEVELOPER_NAME,
       pr.PROJECT_CODE, nvl(pr.PROJECT_NAME_EN,pr.PROJECT_NAME_AR) PROJECT_NAME, s.OUTSTANDING_VALUE, s.PURCHASE_VALUE,
       s.CHEQUE_COVERAGE, s.DOCUMENT_COMPLETION_PCT, s.OPEN_EXCEPTION_COUNT, s.CURRENT_STATUS, s.CREATED_ON
from FNV_PURSHASED_PORTFOLIO_SNAPSHOT s
join FNV_PURSHASED_PORTFOLIO p on p.PORTFOLIO_ID = s.PORTFOLIO_ID
join FNV_REALESTATE_DEVELOPER d on d.DEVELOPER_ID = p.DEVELOPER_ID
join FNV_PROJECT pr on pr.PROJECT_ID = p.PROJECT_ID;
