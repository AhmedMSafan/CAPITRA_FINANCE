select d.DOCUMENT_ID, d.PORTFOLIO_ID, p.PORTFOLIO_NO, d.DOCUMENT_TYPE_CODE, rt.DOCUMENT_TYPE_NAME_AR, rt.DOCUMENT_TYPE_NAME,
       d.EXPIRY_DATE, d.EXPIRY_DATE-trunc(sysdate) DAYS_TO_EXPIRY
from FNV_PURSHASED_PORTFOLIO_DOCUMENT d
join FNV_PURSHASED_PORTFOLIO p on p.PORTFOLIO_ID=d.PORTFOLIO_ID
join REF_DOCUMENT_TYPE rt on rt.DOCUMENT_TYPE_CODE=d.DOCUMENT_TYPE_CODE
where d.EXPIRY_DATE is not null;
