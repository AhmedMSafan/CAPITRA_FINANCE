-- Page 216 Portfolio Purchase Agreement, regions "Agreement", "Agreement Clauses" and "Agreement Annexes".
-- name: HEADER
select p.PORTFOLIO_NO, d.LEGAL_NAME_EN, d.LEGAL_NAME_AR, prj.PROJECT_NAME_EN, prj.PROJECT_NAME_AR, p.CURRENCY_CODE,
       p.PROPOSED_PURCHASE_VALUE, p.PV_RATE, p.RESERVED_AMOUNT_PERCENT, p.LATE_FEE_RATE, p.BOARD_DECISION_NO, p.BOARD_DECISION_DATE
  from FNV_PURSHASED_PORTFOLIO p
  join FNV_REALESTATE_DEVELOPER d on d.DEVELOPER_ID = p.DEVELOPER_ID
  join FNV_PROJECT prj on prj.PROJECT_ID = p.PROJECT_ID
 where p.PORTFOLIO_ID = :P216_PORTFOLIO_ID
-- name: SELECTED
select count(*) N, count(distinct A.UNIT_ID) UNITS, nvl(sum(A.OUTSTANDING_VALUE),0) OV
  from FNV_PURSHASED_PORTFOLIO_ACCOUNT A
 where A.PORTFOLIO_ID = :P216_PORTFOLIO_ID and nvl(A.DEAL_DECISION_CODE,'SELECTED') = 'SELECTED'
-- name: CHEQUES
select count(*) N, nvl(sum(C.CHEQUE_AMOUNT),0) AMT
  from FNV_PURCHASED_PORTFOLIO_CHEQUE C
  join FNV_PURSHASED_PORTFOLIO_ACCOUNT A on A.PORTFOLIO_ACCOUNT_ID = C.PORTFOLIO_ACCOUNT_ID
 where C.PORTFOLIO_ID = :P216_PORTFOLIO_ID and nvl(A.DEAL_DECISION_CODE,'SELECTED') = 'SELECTED'
-- name: CONTRACTS
select nvl(INV.FULL_NAME_EN,INV.FULL_NAME_AR) NE, INV.FULL_NAME_AR NA, A.SELLER_CONTRACT_NO, U.UNIT_CODE, nvl(A.OUTSTANDING_VALUE,0) OV
  from FNV_PURSHASED_PORTFOLIO_ACCOUNT A
  join FNV_INVESTOR INV on INV.INVESTOR_ID = A.INVESTOR_ID
  left join FNV_PROJECT_UNIT U on U.UNIT_ID = A.UNIT_ID
 where A.PORTFOLIO_ID = :P216_PORTFOLIO_ID and nvl(A.DEAL_DECISION_CODE,'SELECTED') = 'SELECTED'
 order by INV.INVESTOR_CODE, A.PORTFOLIO_ACCOUNT_ID
-- name: CHEQUE_LIST
select nvl(INV.FULL_NAME_EN,INV.FULL_NAME_AR) NE, C.CHEQUE_NO, C.BANK_NAME, C.DUE_DATE, C.CHEQUE_AMOUNT
  from FNV_PURCHASED_PORTFOLIO_CHEQUE C
  join FNV_PURSHASED_PORTFOLIO_ACCOUNT A on A.PORTFOLIO_ACCOUNT_ID = C.PORTFOLIO_ACCOUNT_ID
  join FNV_INVESTOR INV on INV.INVESTOR_ID = A.INVESTOR_ID
 where C.PORTFOLIO_ID = :P216_PORTFOLIO_ID and nvl(A.DEAL_DECISION_CODE,'SELECTED') = 'SELECTED'
 order by C.DUE_DATE, C.CHEQUE_ID
