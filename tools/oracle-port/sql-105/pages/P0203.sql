-- Page 203 Portfolio Workspace, regions "Portfolio Overview" and "Portfolio Details".
-- name: PORTFOLIO
select p.PORTFOLIO_ID, p.PORTFOLIO_NO, p.PORTFOLIO_STATUS_CODE, p.DEVELOPER_ID, p.PROJECT_ID, p.CURRENCY_CODE, p.REQUEST_DATE,
       p.FACE_VALUE, p.OUTSTANDING_VALUE, p.PROPOSED_PURCHASE_VALUE, p.EXPECTED_RETURN_AMOUNT,
       p.SELECTED_ACCOUNT_COUNT, p.SELECTED_FACE_VALUE, p.SELECTED_OUTSTANDING_VALUE, p.SELECTED_PAID_VALUE,
       p.LATE_FEE_RATE, p.PV_RATE, p.RESERVED_AMOUNT_PERCENT, p.TERM_MONTHS, p.COVERAGE_PCT, p.MARGIN_PERCENTAGE, p.ADMIN_EXPENSE_PERCENT,
       p.LEGAL_FEE_PER_UNIT, p.VALUATION_FEE_PER_UNIT, p.BOARD_DECISION, p.SUBMITTED_DATE SUBMITTED_DATE, p.APPROVED_DATE APPROVED_DATE,
       p.BOARD_DECISION_NO, p.BOARD_DECISION_DATE, p.REJECTION_REASON, p.COMMENTS, p.WORKFLOW_INSTANCE_ID,
       (select s.STATUS_NAME_EN from REF_PORTFOLIO_STATUS s where s.STATUS_CODE = p.PORTFOLIO_STATUS_CODE) STATUS_NAME,
       (select d.LEGAL_NAME_EN from FNV_REALESTATE_DEVELOPER d where d.DEVELOPER_ID = p.DEVELOPER_ID) DEV,
       (select j.PROJECT_NAME_EN from FNV_PROJECT j where j.PROJECT_ID = p.PROJECT_ID) PROJ
  from FNV_PURSHASED_PORTFOLIO p where p.PORTFOLIO_ID = :P203_PORTFOLIO_ID
-- name: ACCOUNTS
select count(*) ACC_N, nvl(sum(CONTRACT_VALUE),0) CV, nvl(sum(PAID_VALUE),0) PV, nvl(sum(OUTSTANDING_VALUE),0) OV,
       count(case when nvl(DEAL_DECISION_CODE,'SELECTED') <> 'EXCLUDED' then 1 end) IN_N,
       nvl(sum(case when nvl(DEAL_DECISION_CODE,'SELECTED') <> 'EXCLUDED' then CONTRACT_VALUE end),0) IN_CV,
       nvl(sum(case when nvl(DEAL_DECISION_CODE,'SELECTED') <> 'EXCLUDED' then OUTSTANDING_VALUE end),0) IN_OV,
       nvl(sum(case when nvl(DEAL_DECISION_CODE,'SELECTED') <> 'EXCLUDED' then PAID_VALUE end),0) IN_PV,
       count(case when DEAL_DECISION_CODE = 'EXCLUDED' then 1 end) EX_N, count(distinct INVESTOR_ID) INV_N, count(distinct UNIT_ID) UNIT_N,
       sum(ARREARS_AMOUNT) ARR
  from FNV_PURSHASED_PORTFOLIO_ACCOUNT where PORTFOLIO_ID = :P203_PORTFOLIO_ID
-- name: TASKS
select tq.TASK_ID, tq.TASK_STATUS, si.STEP_CODE, si.STEP_NAME, tq.CREATED_AT
  from WFE_TASKS tq join WFE_STEP_INSTANCES si on si.STEP_INSTANCE_ID = tq.STEP_INSTANCE_ID
 where si.WORKFLOW_INSTANCE_ID = (select WORKFLOW_INSTANCE_ID from FNV_PURSHASED_PORTFOLIO where PORTFOLIO_ID = :P203_PORTFOLIO_ID)
 order by tq.TASK_ID
-- name: INVESTORS
select i.INVESTOR_ID, i.INVESTOR_CODE, i.FULL_NAME_EN, i.FULL_NAME_AR, i.NATIONAL_ID,
       count(*) CT, nvl(sum(a.CONTRACT_VALUE),0) CV, nvl(sum(a.OUTSTANDING_VALUE),0) OV, nvl(sum(a.PAID_VALUE),0) PVV,
       case when count(case when a.DEAL_DECISION_CODE = 'EXCLUDED' then 1 end) = 0 then 'SELECTED'
            when count(case when a.DEAL_DECISION_CODE = 'EXCLUDED' then 1 end) = count(*) then 'EXCLUDED' else 'MIXED' end DEC,
       nvl((select ar.RESULT_CODE from FNV_AML_RESULTS ar
             where ar.PORTFOLIO_ID = :P203_PORTFOLIO_ID and ar.SUBJECT_TYPE = 'INVESTOR' and ar.SUBJECT_ID = i.INVESTOR_ID
             order by ar.AML_ID desc fetch first 1 rows only),'NOT_SCREENED') AML
  from FNV_PURSHASED_PORTFOLIO_ACCOUNT a join FNV_INVESTOR i on i.INVESTOR_ID = a.INVESTOR_ID
 where a.PORTFOLIO_ID = :P203_PORTFOLIO_ID
 group by i.INVESTOR_ID, i.INVESTOR_CODE, i.FULL_NAME_EN, i.FULL_NAME_AR, i.NATIONAL_ID
 order by nvl(sum(a.OUTSTANDING_VALUE),0) desc, i.INVESTOR_CODE
-- name: ACCOUNT_LIST
select i.INVESTOR_CODE, nvl(i.FULL_NAME_EN,'-') INVESTOR_NAME, u.UNIT_CODE, pa.CONTRACT_DATE, pa.CONTRACT_VALUE, pa.PAID_VALUE, pa.OUTSTANDING_VALUE,
       pa.INSTALLMENT_AMOUNT, pa.REGULAR_PAYMENT_MONTHS, pa.ARREARS_AMOUNT, pa.ACCOUNT_STATUS
  from FNV_PURSHASED_PORTFOLIO_ACCOUNT pa
  join FNV_INVESTOR i on i.INVESTOR_ID = pa.INVESTOR_ID
  join FNV_PROJECT_UNIT u on u.UNIT_ID = pa.UNIT_ID
 where pa.PORTFOLIO_ID = :P203_PORTFOLIO_ID
 order by i.INVESTOR_CODE, u.UNIT_CODE
-- name: PROJECT
select j.* from FNV_PROJECT j where j.PROJECT_ID = (select PROJECT_ID from FNV_PURSHASED_PORTFOLIO where PORTFOLIO_ID = :P203_PORTFOLIO_ID)
-- name: PROJECT_EXTRA
select d.LEGAL_NAME_EN DEV, d.DEVELOPER_CODE DEV_CODE, j.PROJECT_NAME_EN PROJ, j.PROJECT_NAME_AR PROJ_AR,
       (select count(*) from FNV_PROJECT_UNIT u where u.PROJECT_ID = p.PROJECT_ID) PROJ_UNITS
  from FNV_PURSHASED_PORTFOLIO p
  left join FNV_REALESTATE_DEVELOPER d on d.DEVELOPER_ID = p.DEVELOPER_ID
  left join FNV_PROJECT j on j.PROJECT_ID = p.PROJECT_ID
 where p.PORTFOLIO_ID = :P203_PORTFOLIO_ID
-- name: UNITS
select u.UNIT_CODE, u.UNIT_TYPE_CODE, nvl(i.FULL_NAME_EN,i.FULL_NAME_AR) INV, a.SELLER_CONTRACT_NO, nvl(a.CONTRACT_VALUE,0) CV, nvl(a.DEAL_DECISION_CODE,'SELECTED') DEC
  from FNV_PURSHASED_PORTFOLIO_ACCOUNT a
  join FNV_PROJECT_UNIT u on u.UNIT_ID = a.UNIT_ID
  join FNV_INVESTOR i on i.INVESTOR_ID = a.INVESTOR_ID
 where a.PORTFOLIO_ID = :P203_PORTFOLIO_ID
 order by u.UNIT_CODE
-- name: STATUS_HIST
select FROM_STATUS, TO_STATUS, CHANGE_DATE, CHANGED_BY, COMMENTS from FNV_PURSHASED_PORTFOLIO_STATUS_HIST where PORTFOLIO_ID = :P203_PORTFOLIO_ID order by CHANGE_DATE desc
