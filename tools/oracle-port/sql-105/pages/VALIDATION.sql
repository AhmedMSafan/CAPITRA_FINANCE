-- FNV_VALIDATION_PKG: the readiness checks of a portfolio (:PORTFOLIO_ID).
-- name: DOCUMENT_READY
select DOCUMENT_READY_FLAG from FNV_V_DOCUMENT_COMPLETENESS where PORTFOLIO_ID = :PORTFOLIO_ID
-- name: PAYMENT_PROBLEMS
select count(*) from FNV_V_PAYMENT_REGULARITY where PORTFOLIO_ID = :PORTFOLIO_ID and (PAYMENT_COUNT < 12 or PROBLEM_COUNT > 0)
-- name: VALUATIONS
select count(*) from FNV_VALUATION where PORTFOLIO_ID = :PORTFOLIO_ID
-- name: LEGAL_READY
select LEGAL_READY_FLAG from FNV_V_LEGAL_STATUS where PORTFOLIO_ID = :PORTFOLIO_ID
-- name: COVERAGE_OK
select COVERAGE_OK_FLAG from FNV_V_CHEQUE_COVERAGE where PORTFOLIO_ID = :PORTFOLIO_ID
-- name: GUARANTEE_READY
select GUARANTEE_READY_FLAG from FNV_V_GUARANTEE_STATUS where PORTFOLIO_ID = :PORTFOLIO_ID
-- name: FINANCIAL_STUDIES
select count(*) from FNV_FINANCIAL_STUDY where PORTFOLIO_ID = :PORTFOLIO_ID
