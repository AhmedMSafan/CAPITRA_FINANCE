-- Page 201 Portfolio Cases, region "Portfolio Case Board" (:DEV is P201_DEVELOPER_ID).
-- name: TOTALS
select count(*) TOTAL, count(case when p.WORKFLOW_INSTANCE_ID is not null then 1 end) WF, count(case when v.READY_FOR_SUBMISSION_FLAG = 'Y' then 1 end) READY,
       nvl(sum(v.FACE_VALUE),0) FACE, nvl(sum(v.OUTSTANDING_VALUE),0) OUTSTANDING
  from FNV_V_PORTFOLIO_WORKLIST v left join FNV_PURSHASED_PORTFOLIO p on p.PORTFOLIO_ID = v.PORTFOLIO_ID
 where (:P201_DEVELOPER_ID is null or v.DEVELOPER_ID = :P201_DEVELOPER_ID)
-- name: STATUSES
select v.PORTFOLIO_STATUS_CODE C, nvl(max(rs.STATUS_NAME_EN), v.PORTFOLIO_STATUS_CODE) N, max(rs.STATUS_NAME_AR) NA, count(*) K, nvl(max(rs.DISPLAY_SEQ),999) SEQ
  from FNV_V_PORTFOLIO_WORKLIST v left join REF_PORTFOLIO_STATUS rs on rs.STATUS_CODE = v.PORTFOLIO_STATUS_CODE
 where (:P201_DEVELOPER_ID is null or v.DEVELOPER_ID = :P201_DEVELOPER_ID)
 group by v.PORTFOLIO_STATUS_CODE order by 5, 1
-- name: CASES
select v.PORTFOLIO_ID, v.PORTFOLIO_NO, v.PORTFOLIO_STATUS_CODE, nvl(rs.STATUS_NAME_EN, v.STATUS_NAME_EN) STATUS_EN, rs.STATUS_NAME_AR STATUS_AR,
       nvl(v.DEVELOPER_NAME_EN,'-') DEV, nvl(v.PROJECT_NAME_EN,'-') PROJ, v.REQUEST_DATE, v.FACE_VALUE, v.OUTSTANDING_VALUE, v.PROPOSED_PURCHASE_VALUE,
       v.DOCUMENT_READY_FLAG, v.DD_READY_FLAG, v.PAYMENT_HISTORY_READY_FLAG, v.VALUATION_READY_FLAG, v.LEGAL_READY_FLAG, v.FINANCE_READY_FLAG,
       v.CHEQUE_READY_FLAG, v.GUARANTEE_READY_FLAG, v.READY_FOR_SUBMISSION_FLAG,
       p.WORKFLOW_INSTANCE_ID,
       nvl((select max(si.STEP_NAME) from WFE_STEP_INSTANCES si join WFE_WORKFLOW_INSTANCES wi on wi.WORKFLOW_INSTANCE_ID = si.WORKFLOW_INSTANCE_ID
             where si.WORKFLOW_INSTANCE_ID = p.WORKFLOW_INSTANCE_ID and si.ELEMENT_ID = wi.CURRENT_ELEMENT_ID), v.CURRENT_APPROVAL_STEP) STEP_NAME
  from FNV_V_PORTFOLIO_WORKLIST v
  left join FNV_PURSHASED_PORTFOLIO p on p.PORTFOLIO_ID = v.PORTFOLIO_ID
  left join REF_PORTFOLIO_STATUS rs on rs.STATUS_CODE = v.PORTFOLIO_STATUS_CODE
 where (:P201_DEVELOPER_ID is null or v.DEVELOPER_ID = :P201_DEVELOPER_ID)
 order by v.REQUEST_DATE desc nulls last, v.PORTFOLIO_NO desc
 fetch first 300 rows only
