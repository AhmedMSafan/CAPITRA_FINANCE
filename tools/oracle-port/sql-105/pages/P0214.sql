-- Page 214 Portfolio Financial Review, region "Financial Review".
-- name: HEADER
select p.PORTFOLIO_NO, p.PORTFOLIO_STATUS_CODE, nvl(d.LEGAL_NAME_EN,d.LEGAL_NAME_AR) DEV, p.CURRENCY_CODE,
       p.PV_RATE, p.MARGIN_PERCENTAGE, p.ADMIN_EXPENSE_PERCENT, p.LEGAL_FEE_PER_UNIT, p.VALUATION_FEE_PER_UNIT,
       (select s.STATUS_NAME_EN from REF_PORTFOLIO_STATUS s where s.STATUS_CODE = p.PORTFOLIO_STATUS_CODE) STATUS_NAME
  from FNV_PURSHASED_PORTFOLIO p
  join FNV_REALESTATE_DEVELOPER d on d.DEVELOPER_ID = p.DEVELOPER_ID
 where p.PORTFOLIO_ID = :P214_PORTFOLIO_ID
-- name: SELECTED
select nvl(sum(A.OUTSTANDING_VALUE),0) OV, nvl(sum(A.CONTRACT_VALUE),0) FACE, count(distinct A.UNIT_ID) UNITS
  from FNV_PURSHASED_PORTFOLIO_ACCOUNT A
 where A.PORTFOLIO_ID = :P214_PORTFOLIO_ID and nvl(A.DEAL_DECISION_CODE,'SELECTED') = 'SELECTED'
-- name: CHEQUES
select C.CHEQUE_NO, C.DUE_DATE, C.CHEQUE_AMOUNT, nvl(INV.FULL_NAME_EN,INV.FULL_NAME_AR) INV
  from FNV_PURCHASED_PORTFOLIO_CHEQUE C
  join FNV_PURSHASED_PORTFOLIO_ACCOUNT A on A.PORTFOLIO_ACCOUNT_ID = C.PORTFOLIO_ACCOUNT_ID
  join FNV_INVESTOR INV on INV.INVESTOR_ID = A.INVESTOR_ID
 where C.PORTFOLIO_ID = :P214_PORTFOLIO_ID and nvl(A.DEAL_DECISION_CODE,'SELECTED') = 'SELECTED'
 order by C.DUE_DATE nulls first, C.CHEQUE_ID
