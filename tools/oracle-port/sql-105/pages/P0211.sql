-- Page 211 Portfolio Legal Review, region "Portfolio Legal Review".
-- name: HEADER
select p.PORTFOLIO_NO, p.PORTFOLIO_STATUS_CODE, nvl(d.LEGAL_NAME_EN,d.LEGAL_NAME_AR) DEV, nvl(prj.PROJECT_NAME_EN,prj.PROJECT_NAME_AR) PROJECT,
       (select s.STATUS_NAME_EN from REF_PORTFOLIO_STATUS s where s.STATUS_CODE = p.PORTFOLIO_STATUS_CODE) STATUS_NAME
  from FNV_PURSHASED_PORTFOLIO p
  join FNV_REALESTATE_DEVELOPER d on d.DEVELOPER_ID = p.DEVELOPER_ID
  join FNV_PROJECT prj on prj.PROJECT_ID = p.PROJECT_ID
 where p.PORTFOLIO_ID = :P211_PORTFOLIO_ID
-- name: ROWS
select A.PORTFOLIO_ACCOUNT_ID, INV.INVESTOR_CODE, INV.FULL_NAME_EN, INV.FULL_NAME_AR, A.SELLER_CONTRACT_NO, U.UNIT_CODE,
       nvl(A.CONTRACT_VALUE,0) CV, nvl(A.PAID_VALUE,0) PV, nvl(A.OUTSTANDING_VALUE,0) OV, nvl(A.DEAL_DECISION_CODE,'SELECTED') DEC
  from FNV_PURSHASED_PORTFOLIO_ACCOUNT A
  join FNV_INVESTOR INV on INV.INVESTOR_ID = A.INVESTOR_ID
  left join FNV_PROJECT_UNIT U on U.UNIT_ID = A.UNIT_ID
 where A.PORTFOLIO_ID = :P211_PORTFOLIO_ID
 order by INV.INVESTOR_CODE, A.PORTFOLIO_ACCOUNT_ID
