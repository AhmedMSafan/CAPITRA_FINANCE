-- Page 217 Portfolio Disbursement, region "Disbursement".
-- name: HEADER
select p.PORTFOLIO_NO, p.PORTFOLIO_STATUS_CODE, nvl(d.LEGAL_NAME_EN,d.LEGAL_NAME_AR) DEV, trim(p.CURRENCY_CODE) CURRENCY_CODE
  from FNV_PURSHASED_PORTFOLIO p join FNV_REALESTATE_DEVELOPER d on d.DEVELOPER_ID = p.DEVELOPER_ID
 where p.PORTFOLIO_ID = :P217_PORTFOLIO_ID
-- name: STATUS_NAME
select STATUS_NAME_EN from REF_PORTFOLIO_STATUS where STATUS_CODE = :STATUS
-- name: DONE
select count(*) N from FNV_PP_DISBURSEMENT where PORTFOLIO_ID = :P217_PORTFOLIO_ID
-- name: BANKS
select a.ACCOUNT_ID, a.BANK_ID, b.BANK_NAME_EN, a.ACCOUNT_NO, a.ACCOUNT_REF, a.ACCOUNT_TYPE_CODE, a.PURPOSE_EN
  from TRS_BANK_ACCOUNTS a join TRS_BANKS b on b.BANK_ID = a.BANK_ID
 where a.ACTIVE_FLAG = 'Y' and b.ACTIVE_FLAG = 'Y' and trim(a.CURRENCY_CODE) = :CUR
 order by b.BANK_NAME_EN, a.ACCOUNT_NO
