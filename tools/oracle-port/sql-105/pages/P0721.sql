-- name: PORTFOLIOS
select p.PORTFOLIO_ID,
       nvl(p.OUTSTANDING_VALUE,0) OUTSTANDING_VALUE,
       nvl(p.PROPOSED_PURCHASE_VALUE,0) PURCHASE_VALUE,
       cc.CHEQUE_COVERAGE_PCT CHEQUE_COVERAGE,
       dc.DOCUMENT_COMPLETION_PCT,
       (select count(*) from FNV_V_PORTFOLIO_EXCEPTIONS e where e.PORTFOLIO_ID = p.PORTFOLIO_ID) OPEN_EXCEPTION_COUNT,
       p.PORTFOLIO_STATUS_CODE CURRENT_STATUS
  from FNV_PURSHASED_PORTFOLIO p
  left join FNV_V_CHEQUE_COVERAGE cc on cc.PORTFOLIO_ID = p.PORTFOLIO_ID
  left join FNV_V_DOCUMENT_COMPLETENESS dc on dc.PORTFOLIO_ID = p.PORTFOLIO_ID
-- name: ACCOUNTS
select a.PORTFOLIO_ACCOUNT_ID,
       nvl(a.OUTSTANDING_VALUE,0) OUTSTANDING_VALUE,
       nvl(a.ARREARS_AMOUNT,0) ARREARS_AMOUNT,
       (select min(x.DUE_DATE) from FNV_ACCOUNT_PAYMENT x
         where x.PORTFOLIO_ACCOUNT_ID = a.PORTFOLIO_ACCOUNT_ID and x.DUE_DATE >= to_date(:AS_OF_DATE,'YYYY-MM-DD')) NEXT_DUE_DATE,
       (select x.PAYMENT_STATUS_CODE from FNV_ACCOUNT_PAYMENT x
         where x.PORTFOLIO_ACCOUNT_ID = a.PORTFOLIO_ACCOUNT_ID and x.DUE_DATE <= to_date(:AS_OF_DATE,'YYYY-MM-DD')
         order by x.DUE_DATE desc, x.PAYMENT_ID desc fetch first 1 rows only) PAYMENT_STATUS
  from FNV_PURSHASED_PORTFOLIO_ACCOUNT a
