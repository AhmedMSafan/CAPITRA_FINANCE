-- Page 210 Portfolio Inquiries, region "Portfolio Inquiries".
-- name: TYPES
select INQUIRY_TYPE_CODE C, nvl(INQUIRY_NAME_EN, INQUIRY_TYPE_CODE) N
  from REF_INQUIRY_TYPE
 where nvl(ACTIVE_FLAG,'Y') = 'Y'
 order by DISPLAY_SEQ nulls last, INQUIRY_NAME_EN
-- name: HEADER
select p.PORTFOLIO_NO, p.PORTFOLIO_STATUS_CODE, p.DEVELOPER_ID, p.PROJECT_ID, nvl(d.LEGAL_NAME_EN,d.LEGAL_NAME_AR) DEV, nvl(prj.PROJECT_NAME_EN,prj.PROJECT_NAME_AR) PROJECT,
       (select s.STATUS_NAME_EN from REF_PORTFOLIO_STATUS s where s.STATUS_CODE = p.PORTFOLIO_STATUS_CODE) STATUS_NAME
  from FNV_PURSHASED_PORTFOLIO p
  join FNV_REALESTATE_DEVELOPER d on d.DEVELOPER_ID = p.DEVELOPER_ID
  join FNV_PROJECT prj on prj.PROJECT_ID = p.PROJECT_ID
 where p.PORTFOLIO_ID = :P210_PORTFOLIO_ID
-- name: INQUIRIES
select I.INQUIRY_ID, I.SUBJECT_TYPE, I.SUBJECT_ID, I.INQUIRY_TYPE_CODE, I.INQUIRY_DATE, I.REFERENCE_NO, I.RESULT_CODE, I.RISK_LEVEL_CODE,
       nvl(RT.INQUIRY_NAME_EN, I.INQUIRY_TYPE_CODE) INQUIRY_TYPE, substr(I.RESULT_DETAILS,1,200) DETAILS,
       case upper(I.SUBJECT_TYPE)
         when 'INVESTOR' then (select nvl(X.FULL_NAME_EN,X.FULL_NAME_AR) from FNV_INVESTOR X where X.INVESTOR_ID = I.SUBJECT_ID)
         when 'DEVELOPER' then (select nvl(X.LEGAL_NAME_EN,X.LEGAL_NAME_AR) from FNV_REALESTATE_DEVELOPER X where X.DEVELOPER_ID = I.SUBJECT_ID)
         when 'PROJECT' then (select nvl(X.PROJECT_NAME_EN,X.PROJECT_NAME_AR) from FNV_PROJECT X where X.PROJECT_ID = I.SUBJECT_ID)
         when 'PORTFOLIO' then (select X.PORTFOLIO_NO from FNV_PURSHASED_PORTFOLIO X where X.PORTFOLIO_ID = I.SUBJECT_ID) end SUBJ_NAME
  from FNV_INQUIRY_RESULT I
  left join REF_INQUIRY_TYPE RT on RT.INQUIRY_TYPE_CODE = I.INQUIRY_TYPE_CODE
 where I.PORTFOLIO_ID = :P210_PORTFOLIO_ID
 order by I.INQUIRY_ID desc
-- name: ROWS
select A.PORTFOLIO_ACCOUNT_ID, A.INVESTOR_ID, INV.INVESTOR_CODE, INV.FULL_NAME_EN, INV.FULL_NAME_AR, A.SELLER_CONTRACT_NO, U.UNIT_CODE,
       (select count(*) from FNV_INQUIRY_RESULT Q where Q.PORTFOLIO_ID = A.PORTFOLIO_ID and upper(Q.SUBJECT_TYPE) = 'INVESTOR' and Q.SUBJECT_ID = A.INVESTOR_ID) INQ_N,
       (select Q.RISK_LEVEL_CODE from FNV_INQUIRY_RESULT Q where Q.PORTFOLIO_ID = A.PORTFOLIO_ID and upper(Q.SUBJECT_TYPE) = 'INVESTOR' and Q.SUBJECT_ID = A.INVESTOR_ID
         order by Q.INQUIRY_ID desc fetch first 1 rows only) INQ_RISK,
       nvl(A.CONTRACT_VALUE,0) CV, nvl(A.PAID_VALUE,0) PV, nvl(A.OUTSTANDING_VALUE,0) OV, nvl(A.DEAL_DECISION_CODE,'SELECTED') DEC
  from FNV_PURSHASED_PORTFOLIO_ACCOUNT A
  join FNV_INVESTOR INV on INV.INVESTOR_ID = A.INVESTOR_ID
  left join FNV_PROJECT_UNIT U on U.UNIT_ID = A.UNIT_ID
 where A.PORTFOLIO_ID = :P210_PORTFOLIO_ID
 order by INV.INVESTOR_CODE, A.PORTFOLIO_ACCOUNT_ID
-- name: SUBJECTS
select A.INVESTOR_ID, max(INV.INVESTOR_CODE) CODE, max(nvl(INV.FULL_NAME_EN,INV.FULL_NAME_AR)) NM
  from FNV_PURSHASED_PORTFOLIO_ACCOUNT A
  join FNV_INVESTOR INV on INV.INVESTOR_ID = A.INVESTOR_ID
 where A.PORTFOLIO_ID = :P210_PORTFOLIO_ID
 group by A.INVESTOR_ID
 order by 2
