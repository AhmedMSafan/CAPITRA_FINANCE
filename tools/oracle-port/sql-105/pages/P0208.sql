-- Page 208 Portfolio Excel Import & Validation, region "Load Portfolio Data".
-- name: HEADER
select p.PORTFOLIO_NO, p.PORTFOLIO_STATUS_CODE, nvl(d.LEGAL_NAME_EN,d.LEGAL_NAME_AR) DEV, nvl(prj.PROJECT_NAME_EN,prj.PROJECT_NAME_AR) PROJECT, prj.PROJECT_CODE,
       (select s.STATUS_NAME_EN from REF_PORTFOLIO_STATUS s where s.STATUS_CODE = p.PORTFOLIO_STATUS_CODE) STATUS_NAME
  from FNV_PURSHASED_PORTFOLIO p
  join FNV_REALESTATE_DEVELOPER d on d.DEVELOPER_ID = p.DEVELOPER_ID
  join FNV_PROJECT prj on prj.PROJECT_ID = p.PROJECT_ID
 where p.PORTFOLIO_ID = :P208_PORTFOLIO_ID
-- name: KPIS
select count(*) K_N, count(distinct INVESTOR_ID) K_INV, count(distinct UNIT_ID) K_UNIT, nvl(sum(CONTRACT_VALUE),0) K_CV, nvl(sum(PAID_VALUE),0) K_PV,
       nvl(sum(OUTSTANDING_VALUE),0) K_OV, nvl(sum(ARREARS_AMOUNT),0) K_AR
  from FNV_PURSHASED_PORTFOLIO_ACCOUNT where PORTFOLIO_ID = :P208_PORTFOLIO_ID
-- name: ACCOUNTS
select i.INVESTOR_CODE, nvl(i.FULL_NAME_EN,i.FULL_NAME_AR) INV, u.UNIT_CODE, pa.SELLER_CONTRACT_NO, pa.CONTRACT_VALUE, pa.PAID_VALUE, pa.OUTSTANDING_VALUE, pa.ARREARS_AMOUNT
  from FNV_PURSHASED_PORTFOLIO_ACCOUNT pa join FNV_INVESTOR i on i.INVESTOR_ID = pa.INVESTOR_ID left join FNV_PROJECT_UNIT u on u.UNIT_ID = pa.UNIT_ID
 where pa.PORTFOLIO_ID = :P208_PORTFOLIO_ID order by i.INVESTOR_CODE, u.UNIT_CODE fetch first 200 rows only
