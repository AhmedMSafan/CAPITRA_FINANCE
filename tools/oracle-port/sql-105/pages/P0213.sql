-- Page 213 Portfolio Cheque Coverage Review, region "Cheque Coverage Review".
-- name: HEADER
select p.PORTFOLIO_NO, p.PORTFOLIO_STATUS_CODE, nvl(d.LEGAL_NAME_EN,d.LEGAL_NAME_AR) DEV, p.CURRENCY_CODE,
       (select s.STATUS_NAME_EN from REF_PORTFOLIO_STATUS s where s.STATUS_CODE = p.PORTFOLIO_STATUS_CODE) STATUS_NAME
  from FNV_PURSHASED_PORTFOLIO p
  join FNV_REALESTATE_DEVELOPER d on d.DEVELOPER_ID = p.DEVELOPER_ID
 where p.PORTFOLIO_ID = :P213_PORTFOLIO_ID
-- name: TOTALS
select nvl(sum(C.CHEQUE_AMOUNT),0) ALL_AMT, nvl(sum(case when nvl(A.DEAL_DECISION_CODE,'SELECTED') = 'SELECTED' then C.CHEQUE_AMOUNT end),0) INV_AMT
  from FNV_PURCHASED_PORTFOLIO_CHEQUE C
  left join FNV_PURSHASED_PORTFOLIO_ACCOUNT A on A.PORTFOLIO_ACCOUNT_ID = C.PORTFOLIO_ACCOUNT_ID
 where C.PORTFOLIO_ID = :P213_PORTFOLIO_ID
-- name: INVESTORS
select A.INVESTOR_ID, max(INV.INVESTOR_CODE) INVESTOR_CODE, max(INV.FULL_NAME_EN) FULL_NAME_EN, max(INV.FULL_NAME_AR) FULL_NAME_AR, count(*) N,
       sum(nvl(A.OUTSTANDING_VALUE,0)) OV,
       listagg(A.SELLER_CONTRACT_NO||' '||U.UNIT_CODE, ' ') within group (order by A.PORTFOLIO_ACCOUNT_ID) KEYS
  from FNV_PURSHASED_PORTFOLIO_ACCOUNT A
  join FNV_INVESTOR INV on INV.INVESTOR_ID = A.INVESTOR_ID
  left join FNV_PROJECT_UNIT U on U.UNIT_ID = A.UNIT_ID
 where A.PORTFOLIO_ID = :P213_PORTFOLIO_ID and nvl(A.DEAL_DECISION_CODE,'SELECTED') = 'SELECTED'
 group by A.INVESTOR_ID
 order by max(INV.INVESTOR_CODE)
-- name: CHEQUES
select C.CHEQUE_ID, C.PORTFOLIO_ACCOUNT_ID, A.INVESTOR_ID, C.CHEQUE_NO, C.BANK_NAME, C.CHEQUE_DATE, C.DUE_DATE, C.CHEQUE_AMOUNT,
       case when C.ENDORSED_TO_COMPANY_FLAG = 'Y' then 'Y' else 'N' end ENDORSED,
       C.CHEQUE_STATUS_CODE, C.CLEARING_DATE, C.RETURN_REASON, A.SELLER_CONTRACT_NO, U.UNIT_CODE
  from FNV_PURCHASED_PORTFOLIO_CHEQUE C
  join FNV_PURSHASED_PORTFOLIO_ACCOUNT A on A.PORTFOLIO_ACCOUNT_ID = C.PORTFOLIO_ACCOUNT_ID
  left join FNV_PROJECT_UNIT U on U.UNIT_ID = A.UNIT_ID
 where C.PORTFOLIO_ID = :P213_PORTFOLIO_ID and nvl(A.DEAL_DECISION_CODE,'SELECTED') = 'SELECTED'
 order by C.DUE_DATE nulls last, C.CHEQUE_ID
-- name: STATUSES
select CHEQUE_STATUS_CODE from REF_CHEQUE_STATUS order by CHEQUE_STATUS_CODE
-- name: ACCOUNTS
select A.PORTFOLIO_ACCOUNT_ID, A.INVESTOR_ID, A.SELLER_CONTRACT_NO, U.UNIT_CODE, nvl(A.OUTSTANDING_VALUE,0) OV
  from FNV_PURSHASED_PORTFOLIO_ACCOUNT A
  left join FNV_PROJECT_UNIT U on U.UNIT_ID = A.UNIT_ID
 where A.PORTFOLIO_ID = :P213_PORTFOLIO_ID and nvl(A.DEAL_DECISION_CODE,'SELECTED') = 'SELECTED'
 order by A.PORTFOLIO_ACCOUNT_ID
