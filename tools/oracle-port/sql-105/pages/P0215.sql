-- Page 215 Portfolio Board Review, regions "Board Report" and "Board Report Details".
-- name: HEADER
select p.PORTFOLIO_NO, p.PORTFOLIO_STATUS_CODE, nvl(d.LEGAL_NAME_EN,d.LEGAL_NAME_AR) DEV, nvl(prj.PROJECT_NAME_EN,prj.PROJECT_NAME_AR) PRJ, p.CURRENCY_CODE,
       p.COVERAGE_PCT, p.MARGIN_PERCENTAGE, p.PV_RATE, p.RESERVED_AMOUNT_PERCENT, p.LATE_FEE_RATE, p.ADMIN_EXPENSE_PERCENT, p.LEGAL_FEE_PER_UNIT, p.VALUATION_FEE_PER_UNIT, p.TERM_MONTHS,
       (select s.STATUS_NAME_EN from REF_PORTFOLIO_STATUS s where s.STATUS_CODE = p.PORTFOLIO_STATUS_CODE) STATUS_NAME
  from FNV_PURSHASED_PORTFOLIO p
  join FNV_REALESTATE_DEVELOPER d on d.DEVELOPER_ID = p.DEVELOPER_ID
  join FNV_PROJECT prj on prj.PROJECT_ID = p.PROJECT_ID
 where p.PORTFOLIO_ID = :P215_PORTFOLIO_ID
-- name: ACCOUNTS
select nvl(sum(A.CONTRACT_VALUE),0) FACE, nvl(sum(A.OUTSTANDING_VALUE),0) OUT, nvl(sum(A.PAID_VALUE),0) PAID, count(*) N, count(distinct A.INVESTOR_ID) INV,
       nvl(sum(case when nvl(A.DEAL_DECISION_CODE,'SELECTED') = 'SELECTED' then A.CONTRACT_VALUE end),0) SFACE,
       nvl(sum(case when nvl(A.DEAL_DECISION_CODE,'SELECTED') = 'SELECTED' then A.OUTSTANDING_VALUE end),0) SOUT,
       nvl(sum(case when nvl(A.DEAL_DECISION_CODE,'SELECTED') = 'SELECTED' then A.PAID_VALUE end),0) SPAID,
       count(case when nvl(A.DEAL_DECISION_CODE,'SELECTED') = 'SELECTED' then 1 end) SN,
       count(distinct case when nvl(A.DEAL_DECISION_CODE,'SELECTED') = 'SELECTED' then A.INVESTOR_ID end) SINV,
       count(distinct case when nvl(A.DEAL_DECISION_CODE,'SELECTED') = 'SELECTED' then A.UNIT_ID end) UNITS
  from FNV_PURSHASED_PORTFOLIO_ACCOUNT A
 where A.PORTFOLIO_ID = :P215_PORTFOLIO_ID
-- name: CHEQUES
select count(*) N, nvl(sum(C.CHEQUE_AMOUNT),0) AMT
  from FNV_PURCHASED_PORTFOLIO_CHEQUE C
  join FNV_PURSHASED_PORTFOLIO_ACCOUNT A on A.PORTFOLIO_ACCOUNT_ID = C.PORTFOLIO_ACCOUNT_ID
 where C.PORTFOLIO_ID = :P215_PORTFOLIO_ID and nvl(A.DEAL_DECISION_CODE,'SELECTED') = 'SELECTED'
-- name: AML
select count(*) N, count(case when upper(nvl(R.RESULT_CODE,'X')) <> 'CLEAR' then 1 end) FLAG
  from FNV_AML_RESULTS R
 where R.PORTFOLIO_ID = :P215_PORTFOLIO_ID
-- name: INQ
select count(*) N, count(case when upper(Q.RISK_LEVEL_CODE) in ('HIGH','CRITICAL') then 1 end) HIGH
  from FNV_INQUIRY_RESULT Q
 where Q.PORTFOLIO_ID = :P215_PORTFOLIO_ID
-- name: VALUATION
select V.MARKET_VALUE, V.RECOMMENDED_VALUE, V.VALUATION_DATE, V.VALUER_NAME, V.PROJECT_COMPLETION_PCT
  from FNV_VALUATION V
 where V.PORTFOLIO_ID = :P215_PORTFOLIO_ID
 order by V.VALUATION_DATE desc nulls last, V.VALUATION_ID desc
 fetch first 1 rows only
-- name: INVESTORS
select A.INVESTOR_ID, max(nvl(INV.FULL_NAME_EN,INV.FULL_NAME_AR)) NM, max(INV.INVESTOR_CODE) CD, count(*) N, sum(nvl(A.OUTSTANDING_VALUE,0)) OV, sum(nvl(A.CONTRACT_VALUE,0)) CV, sum(nvl(A.PAID_VALUE,0)) PV,
       count(case when nvl(A.DEAL_DECISION_CODE,'SELECTED') = 'SELECTED' then 1 end) SN,
       (select nvl(sum(C.CHEQUE_AMOUNT),0) from FNV_PURCHASED_PORTFOLIO_CHEQUE C join FNV_PURSHASED_PORTFOLIO_ACCOUNT A2 on A2.PORTFOLIO_ACCOUNT_ID = C.PORTFOLIO_ACCOUNT_ID
         where C.PORTFOLIO_ID = :P215_PORTFOLIO_ID and A2.INVESTOR_ID = A.INVESTOR_ID) CHQ
  from FNV_PURSHASED_PORTFOLIO_ACCOUNT A
  join FNV_INVESTOR INV on INV.INVESTOR_ID = A.INVESTOR_ID
 where A.PORTFOLIO_ID = :P215_PORTFOLIO_ID
 group by A.INVESTOR_ID
 order by count(case when nvl(A.DEAL_DECISION_CODE,'SELECTED') = 'SELECTED' then 1 end) desc, max(INV.INVESTOR_CODE)
