-- Page 401 Portfolio Valuation, region "Portfolio Valuation".
-- name: HEADER
select p.PORTFOLIO_NO, p.PORTFOLIO_STATUS_CODE, nvl(d.LEGAL_NAME_EN,d.LEGAL_NAME_AR) DEV, nvl(prj.PROJECT_NAME_EN,prj.PROJECT_NAME_AR) PROJECT,
       p.FACE_VALUE, p.OUTSTANDING_VALUE, p.PROPOSED_PURCHASE_VALUE, nvl(p.CURRENCY_CODE,'EGP') CUR,
       (select s.STATUS_NAME_EN from REF_PORTFOLIO_STATUS s where s.STATUS_CODE = p.PORTFOLIO_STATUS_CODE) STATUS_NAME
  from FNV_PURSHASED_PORTFOLIO p
  join FNV_REALESTATE_DEVELOPER d on d.DEVELOPER_ID = p.DEVELOPER_ID
  join FNV_PROJECT prj on prj.PROJECT_ID = p.PROJECT_ID
 where p.PORTFOLIO_ID = :P401_PORTFOLIO_ID
-- name: TYPES
select VALUATION_TYPE_CODE C, nvl(VALUATION_NAME_EN, VALUATION_TYPE_CODE) N
  from REF_VALUATION_TYPE
 where nvl(ACTIVE_FLAG,'Y') = 'Y'
 order by DISPLAY_SEQ nulls last, VALUATION_TYPE_CODE
-- name: UNITS
select U.UNIT_ID, U.UNIT_CODE||' - '||nvl(UT.UNIT_TYPE_NAME_EN,'-') D
  from FNV_PROJECT_UNIT U
  join FNV_PURSHASED_PORTFOLIO P on P.PROJECT_ID = U.PROJECT_ID
  left join REF_UNIT_TYPE UT on UT.UNIT_TYPE_CODE = U.UNIT_TYPE_CODE
 where P.PORTFOLIO_ID = :P401_PORTFOLIO_ID and U.ACTIVE_FLAG = 'Y'
 order by U.UNIT_CODE
-- name: DOCS
select D.DOCUMENT_ID, nvl(D.DOCUMENT_NO,D.FILE_NAME)||' - '||nvl(RT.DOCUMENT_TYPE_NAME,'-') D
  from FNV_PURSHASED_PORTFOLIO_DOCUMENT D
  join REF_DOCUMENT_TYPE RT on RT.DOCUMENT_TYPE_CODE = D.DOCUMENT_TYPE_CODE
 where D.PORTFOLIO_ID = :P401_PORTFOLIO_ID and D.DOCUMENT_TYPE_CODE = 'VALUATION_REPORT'
 order by D.DOCUMENT_ID desc
-- name: VALUATIONS
select V.VALUATION_ID, nvl(RT.VALUATION_NAME_EN, V.VALUATION_TYPE_CODE) VTYPE, V.VALUER_NAME, V.VALUER_REGISTRATION_NO, V.VALUATION_DATE,
       V.MARKET_VALUE, V.RECOMMENDED_VALUE, V.PROJECT_COMPLETION_PCT, V.REPORT_DOCUMENT_ID, V.APPROVED_BY, V.APPROVED_DATE, U.UNIT_CODE
  from FNV_VALUATION V
  left join REF_VALUATION_TYPE RT on RT.VALUATION_TYPE_CODE = V.VALUATION_TYPE_CODE
  left join FNV_PROJECT_UNIT U on U.UNIT_ID = V.UNIT_ID
 where V.PORTFOLIO_ID = :P401_PORTFOLIO_ID
 order by V.VALUATION_DATE desc nulls last, V.VALUATION_ID desc
