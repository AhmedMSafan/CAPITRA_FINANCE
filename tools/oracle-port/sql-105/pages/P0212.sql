-- Page 212 Portfolio Coverage Review, region "Coverage Review".
-- name: HEADER
select p.PORTFOLIO_NO, p.PORTFOLIO_STATUS_CODE, nvl(d.LEGAL_NAME_EN,d.LEGAL_NAME_AR) DEV, nvl(prj.PROJECT_NAME_EN,prj.PROJECT_NAME_AR) PROJECT, p.COVERAGE_PCT, p.CURRENCY_CODE,
       (select s.STATUS_NAME_EN from REF_PORTFOLIO_STATUS s where s.STATUS_CODE = p.PORTFOLIO_STATUS_CODE) STATUS_NAME
  from FNV_PURSHASED_PORTFOLIO p
  join FNV_REALESTATE_DEVELOPER d on d.DEVELOPER_ID = p.DEVELOPER_ID
  join FNV_PROJECT prj on prj.PROJECT_ID = p.PROJECT_ID
 where p.PORTFOLIO_ID = :P212_PORTFOLIO_ID
-- name: INVESTORS
select A.INVESTOR_ID, max(INV.INVESTOR_CODE) INVESTOR_CODE, max(INV.FULL_NAME_EN) FULL_NAME_EN, max(INV.FULL_NAME_AR) FULL_NAME_AR, count(*) N,
       sum(nvl(A.CONTRACT_VALUE,0)) CV, sum(nvl(A.PAID_VALUE,0)) PV,
       count(case when A.DEAL_DECISION_CODE = 'EXCLUDED' then 1 end) EXC,
       listagg(A.SELLER_CONTRACT_NO||' '||U.UNIT_CODE, ' ') within group (order by A.PORTFOLIO_ACCOUNT_ID) KEYS
  from FNV_PURSHASED_PORTFOLIO_ACCOUNT A
  join FNV_INVESTOR INV on INV.INVESTOR_ID = A.INVESTOR_ID
  left join FNV_PROJECT_UNIT U on U.UNIT_ID = A.UNIT_ID
 where A.PORTFOLIO_ID = :P212_PORTFOLIO_ID
 group by A.INVESTOR_ID
 order by case when sum(nvl(A.CONTRACT_VALUE,0)) > 0 then sum(nvl(A.PAID_VALUE,0))/sum(nvl(A.CONTRACT_VALUE,0)) end nulls first, max(INV.INVESTOR_CODE)
-- name: CONTRACTS
select A.SELLER_CONTRACT_NO, U.UNIT_CODE, nvl(A.CONTRACT_VALUE,0) CV, nvl(A.PAID_VALUE,0) PV, nvl(A.DEAL_DECISION_CODE,'SELECTED') DEC
  from FNV_PURSHASED_PORTFOLIO_ACCOUNT A
  left join FNV_PROJECT_UNIT U on U.UNIT_ID = A.UNIT_ID
 where A.PORTFOLIO_ID = :P212_PORTFOLIO_ID and A.INVESTOR_ID = :INVESTOR_ID
 order by A.PORTFOLIO_ACCOUNT_ID
