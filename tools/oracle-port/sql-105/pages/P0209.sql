-- Page 209 Portfolio AML Review, region "AML Review" and its processes.
-- name: HEADER
select p.PORTFOLIO_NO, p.PORTFOLIO_STATUS_CODE, p.DEVELOPER_ID, nvl(d.LEGAL_NAME_EN,d.LEGAL_NAME_AR) DEV, nvl(prj.PROJECT_NAME_EN,prj.PROJECT_NAME_AR) PROJECT,
       (select s.STATUS_NAME_EN from REF_PORTFOLIO_STATUS s where s.STATUS_CODE = p.PORTFOLIO_STATUS_CODE) STATUS_NAME
  from FNV_PURSHASED_PORTFOLIO p
  join FNV_REALESTATE_DEVELOPER d on d.DEVELOPER_ID = p.DEVELOPER_ID
  join FNV_PROJECT prj on prj.PROJECT_ID = p.PROJECT_ID
 where p.PORTFOLIO_ID = :P209_PORTFOLIO_ID
-- name: DEV_STATUS
select (select RESULT_CODE from FNV_AML_RESULTS where PORTFOLIO_ID = :P209_PORTFOLIO_ID and SUBJECT_TYPE = 'DEVELOPER' and SUBJECT_ID = :DEVELOPER_ID order by AML_ID desc fetch first 1 rows only) RESULT_CODE from dual
-- name: ROWS
select a.PORTFOLIO_ACCOUNT_ID, a.INVESTOR_ID, inv.INVESTOR_CODE, inv.FULL_NAME_EN, inv.FULL_NAME_AR,
       a.SELLER_CONTRACT_NO, u.UNIT_CODE, nvl(a.CONTRACT_VALUE,0) CV, nvl(a.PAID_VALUE,0) PV, nvl(a.OUTSTANDING_VALUE,0) OV, a.DEAL_DECISION_CODE,
       nvl((select ar.RESULT_CODE from FNV_AML_RESULTS ar
             where ar.PORTFOLIO_ID = a.PORTFOLIO_ID and ar.SUBJECT_TYPE = 'INVESTOR' and ar.SUBJECT_ID = a.INVESTOR_ID
             order by ar.AML_ID desc fetch first 1 rows only),'NOT_SCREENED') AML_STATUS
  from FNV_PURSHASED_PORTFOLIO_ACCOUNT a
  join FNV_INVESTOR inv on inv.INVESTOR_ID = a.INVESTOR_ID
  left join FNV_PROJECT_UNIT u on u.UNIT_ID = a.UNIT_ID
 where a.PORTFOLIO_ID = :P209_PORTFOLIO_ID
 order by inv.INVESTOR_CODE, a.PORTFOLIO_ACCOUNT_ID
-- name: LOG
select x.SUBJECT_TYPE, x.SUBJECT_ID, x.AML_TYPE_CODE, x.RESULT_CODE, x.RISK_LEVEL_CODE, x.MATCH_SCORE_PCT, x.SCREENING_DATE, x.REFERENCE_NO,
       substr(x.RESULT_DETAILS,1,300) DETAILS,
       case when x.SUBJECT_TYPE = 'DEVELOPER'
            then (select nvl(d.LEGAL_NAME_EN,d.LEGAL_NAME_AR) from FNV_REALESTATE_DEVELOPER d where d.DEVELOPER_ID = x.SUBJECT_ID)
            else (select nvl(i.FULL_NAME_EN,i.FULL_NAME_AR) from FNV_INVESTOR i where i.INVESTOR_ID = x.SUBJECT_ID) end SUBJECT_NAME
  from FNV_AML_RESULTS x
 where x.PORTFOLIO_ID = :P209_PORTFOLIO_ID
 order by x.AML_ID desc
