select p."PROJECT_ID", p."PROJECT_CODE", p."PROJECT_NAME_AR", p."PROJECT_NAME_EN", count(distinct pf."PORTFOLIO_ID") "PORTFOLIO_COUNT", count(distinct pa."INVESTOR_ID") "INVESTOR_COUNT", sum(pf."PROPOSED_PURCHASE_VALUE") "PURCHASE_VALUE", sum(pf."OUTSTANDING_VALUE") "OUTSTANDING_EXPOSURE"
from "MTG_PROJECTS" p
left join "MTG_PURCHASED_PORTFOLIOS" pf on pf."PROJECT_ID" = p."PROJECT_ID"
left join "MTG_PURCHASED_PORTFOLIO_ACCOUNTS" pa on pa."PORTFOLIO_ID" = pf."PORTFOLIO_ID"
group by p."PROJECT_ID", p."PROJECT_CODE", p."PROJECT_NAME_AR", p."PROJECT_NAME_EN"
