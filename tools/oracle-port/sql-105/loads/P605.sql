select a.PORTFOLIO_ID P605_PORTFOLIO_ID, a.STEP_CODE P605_STEP_CODE, p.PORTFOLIO_NO P605_PORTFOLIO_NO, s.STEP_NAME_EN P605_STEP_NAME,
       nvl(d.LEGAL_NAME_EN,'-')||' | '||nvl(prj.PROJECT_NAME_EN,'-') P605_DEVELOPER_PROJECT,
       to_char(p.PROPOSED_PURCHASE_VALUE,'FM999G999G999G990D00')||' '||p.CURRENCY_CODE P605_PURCHASE_VALUE,
       nvl(a.ASSIGNED_TO,'Unassigned') P605_ASSIGNED_TO, to_char(a.ASSIGNED_DATE,'DD-MON-YYYY') P605_ASSIGNED_DATE,
       p.BOARD_DECISION_NO P605_BOARD_DECISION_NO, to_char(p.BOARD_DECISION_DATE,'YYYY-MM-DD') P605_BOARD_DECISION_DATE, p.BOARD_DECISION P605_BOARD_DECISION
