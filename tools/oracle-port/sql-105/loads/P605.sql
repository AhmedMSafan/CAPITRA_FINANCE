  join FNV_PURSHASED_PORTFOLIO p on p.PORTFOLIO_ID=a.PORTFOLIO_ID
  join REF_APPROVAL_STEP s on s.STEP_CODE=a.STEP_CODE
  join FNV_REALESTATE_DEVELOPER d on d.DEVELOPER_ID=p.DEVELOPER_ID
  join FNV_PROJECT prj on prj.PROJECT_ID=p.PROJECT_ID
 where a.APPROVAL_ID=:P605_APPROVAL_ID
