#!/usr/bin/env python3
"""
Turns the FINOVA Oracle CSV export into one PostgreSQL script that loads CAPITRA_DB,
using the column maps written by gen.py (map-<module>.json).

  Y/N flags -> true/false, DATE -> date, timestamps -> timestamptz (taken as UTC),
  missing audit values -> 'MIGRATION' / now(), ROW_VERSION -> 0.

The script empties the tables it loads, loads them with foreign key checks off
(session_replication_role = replica, so run it as the postgres user),
then moves every identity past the highest loaded key.

usage: load.py <data dir> <output.sql> map-gl.json [map-fin.json ...]
"""
import csv
import json
import os
import sys

csv.field_size_limit(1 << 30)


def lit(value, kind):
    if value is None or value == '':
        return 'NULL'
    if kind == 'flag':
        return 'TRUE' if value.strip().upper() == 'Y' else 'FALSE'
    if kind == 'int':
        return str(int(float(value)))
    if kind == 'decimal':
        return value
    if kind == 'date':
        return "'" + value[:10] + "'"
    if kind in ('datetime', 'audit_at'):
        return "'" + value + "+00'"
    if kind == 'blob':
        return 'NULL'
    return "'" + value.replace("'", "''") + "'"


def main():
    data_dir, out = sys.argv[1], sys.argv[2]
    maps = {}
    for m in sys.argv[3:]:
        maps.update(json.load(open(m)))

    lines = ['-- Generated by tools/oracle-port/load.py from the FINOVA APEX export. Run as postgres in CAPITRA_DB.',
             'BEGIN;', 'SET session_replication_role = replica;', '']
    lines.append('TRUNCATE ' + ', '.join(f'"{m["table"]}"' for m in maps.values()) + ' RESTART IDENTITY;')
    lines.append('')
    total = 0
    for oracle, m in sorted(maps.items()):
        path = os.path.join(data_dir, oracle + '.csv')
        with open(path, encoding='utf-8', newline='') as f:
            rows = list(csv.DictReader(f))
        if not rows:
            continue
        cols = m['columns']
        names = [c['column'] for c in cols.values()]
        has = set(names)
        extra = []
        if 'CREATED_BY' not in has:
            extra.append(('CREATED_BY', "'MIGRATION'"))
        if 'CREATED_AT' not in has:
            extra.append(('CREATED_AT', 'now()'))
        extra.append(('ROW_VERSION', '0'))
        head = ', '.join(f'"{n}"' for n in names + [e[0] for e in extra])
        lines.append(f'-- {oracle}: {len(rows)} rows')
        for r in rows:
            vals = []
            for oc, c in cols.items():
                v = r.get(oc)
                kind = c['kind']
                if kind == 'audit':
                    if c['column'] == 'CREATED_BY':
                        vals.append(lit(v, 'string') if v else "'MIGRATION'")
                    elif c['column'] == 'CREATED_AT':
                        vals.append(lit(v, 'audit_at') if v else 'now()')
                    else:
                        vals.append(lit(v, 'audit_at' if c['column'].endswith('_AT') else 'string'))
                else:
                    vals.append(lit(v, kind))
            vals += [e[1] for e in extra]
            lines.append(f'INSERT INTO "{m["table"]}" ({head}) VALUES ({", ".join(vals)});')
        total += len(rows)
        if m.get('pk') and any(c['column'] == m['pk'] and c['kind'] == 'int' for c in cols.values()):
            lines.append(f"SELECT setval(pg_get_serial_sequence('\"{m['table']}\"', '{m['pk']}'), "
                         f"GREATEST((SELECT MAX(\"{m['pk']}\") FROM \"{m['table']}\"), 1));")
        lines.append('')
    lines += ['SET session_replication_role = DEFAULT;', 'COMMIT;', '']
    with open(out, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))
    print(f'{total} rows from {len(maps)} tables -> {out}')


if __name__ == '__main__':
    main()
