#!/usr/bin/env python3
"""The Navigation Menu list of an APEX application export as a TypeScript tree (label, page, icon, current-for pages).

usage: apex_nav.py <export.sql> <app> <out.ts> [breadcrumb.json]
With breadcrumb.json (the split export's folder, for apex_wizard.py): the Breadcrumb's entries by id.
"""
import html
import json
import re
import sys

src, app, out = sys.argv[1], int(sys.argv[2]), sys.argv[3]
text = open(src, encoding='utf-8').read()

# the list's items follow its create_list call, up to the next list
start = text.index("p_name=>'Navigation Menu'")
end = text.find("wwv_flow_imp_shared.create_list(", start)
chunk = text[start:end if end > 0 else len(text)]
ATTR = re.compile(r"p_(\w+)=>(?:wwv_flow_imp\.id\((\d+)\)|'((?:[^']|'')*)'|(\d+))")
items = []
for call in re.findall(r"wwv_flow_imp_shared\.create_list_item\((.*?)\n\);", chunk, re.S):
    attr = {k: a or c or b.replace("''", "'") for k, a, b, c in ATTR.findall(call)}
    target = attr.get('list_item_link_target', '')
    tm = re.match(r"f\?p=&APP_ID\.:(\d+):&APP_SESSION\.::&DEBUG\.:([^:]*):", target)
    current = attr.get('list_item_current_for_pages')
    items.append({
        'id': attr['id'],
        'parent': attr.get('parent_list_item_id'),
        'seq': int(attr.get('list_item_display_sequence', 0)),
        'label': attr['list_item_link_text'],
        'page': int(tm.group(1)) if tm else None,
        **({'clear': tm.group(2)} if tm and tm.group(2) else {}),
        'icon': attr.get('list_item_icon', ''),
        # Current for pages (COLON_DELIMITED_PAGE_LIST); else the item is current on its own page (TARGET_PAGE)
        **({'current': [int(p) for p in current.split(',')]} if current else {}),
    })


def tree(parent):
    nodes = sorted((i for i in items if i['parent'] == parent), key=lambda i: i['seq'])
    res = []
    for n in nodes:
        node = {k: v for k, v in n.items() if k not in ('id', 'parent', 'seq')}
        kids = tree(n['id'])
        if kids:
            node['children'] = kids
        res.append(node)
    return res


roots = tree(None)
with open(out, 'w', encoding='utf-8') as f:
    f.write(f"// Generated by tools/oracle-port/apex_nav.py from the App {app} export: its Navigation Menu list. Do not edit.\n")
    f.write("/** A menu entry: its page (null: no link), the clear cache of its link, and the pages it is current for (else its own). */\n")
    f.write("export type NavItem = { label: string; page: number | null; clear?: string; icon: string; current?: number[]; children?: NavItem[] }\n\n")
    f.write("export const navMenu: NavItem[] = " + json.dumps(roots, ensure_ascii=False, indent=2) + "\n")
print(len(items), 'items,', len(roots), 'top level')

if len(sys.argv) > 4:
    crumbs = {}
    for call in re.findall(r"wwv_flow_imp_shared\.create_menu_option\((.*?)\n\);", text, re.S):
        attr = {k: a or c or b.replace("''", "'") for k, a, b, c in ATTR.findall(call)}
        lm = re.match(r"f\?p=&APP_ID\.:(\d+):", attr.get('link', ''))
        crumbs[attr['id']] = {'label': html.unescape(attr['short_name']), 'page': int(attr['page_id']) if attr.get('page_id') else None,
                              'link': int(lm.group(1)) if lm else None, 'parent': attr.get('parent_id')}
    json.dump(crumbs, open(sys.argv[4], 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print(len(crumbs), 'breadcrumb entries')
