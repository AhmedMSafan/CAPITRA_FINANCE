select a."APPLICATION_ID", a."APPLICATION_NO", p."FULL_NAME_AR" "APPLICANT_NAME_AR", o."ORG_NAME_AR" "FINANCIER_NAME_AR", a."STATUS_CODE", a."APPROVED_FINANCE_AMOUNT", a."TOTAL_SUBSIDY_AMOUNT", sa."APPROVAL_NO" "SUBSIDY_APPROVAL_NO", sa."APPROVAL_DATE", sa."EXPIRY_DATE", fo."OFFER_NO", fo."EXPIRY_DATE" "OFFER_EXPIRY_DATE"
from "MFF_APPLICATIONS" a
join "MFF_PERSONS" p on p."PERSON_ID" = a."PRIMARY_PERSON_ID"
join "MFF_ORGANIZATIONS" o on o."ORG_ID" = a."FINANCIER_ID"
left join "MFF_SUBSIDY_APPROVALS" sa on sa."APPLICATION_ID" = a."APPLICATION_ID"
left join "MFF_FINANCE_OFFERS" fo on fo."APPLICATION_ID" = a."APPLICATION_ID"
where a."STATUS_CODE" in ('CREDIT_APPROVED', 'CONDITIONAL_APPROVAL', 'OFFERED', 'SUBSIDY_PENDING', 'CONTRACT_PENDING')
