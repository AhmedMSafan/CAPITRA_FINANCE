select a."FINANCIER_ID", o."ORG_NAME_AR" "FINANCIER_NAME_AR", d."STAGE_CODE", s."NAME_AR" "STAGE_NAME_AR", count(distinct d."LOAN_ID") "LOAN_COUNT", sum(coalesce(d."OVERDUE_AMOUNT", 0)) "OVERDUE_AMOUNT", sum(coalesce(l."OUTSTANDING_PRINCIPAL", 0)) "OUTSTANDING_PRINCIPAL"
from "MFF_DELINQUENCIES" d
join "MFF_LOANS" l on l."LOAN_ID" = d."LOAN_ID"
join "MFF_APPLICATIONS" a on a."APPLICATION_ID" = l."APPLICATION_ID"
join "MFF_ORGANIZATIONS" o on o."ORG_ID" = a."FINANCIER_ID"
join "MFF_LKP_DELINQUENCY_STAGES" s on s."CODE" = d."STAGE_CODE"
where coalesce(d."DELINQUENCY_STATUS", 'OPEN') <> 'CLOSED'
group by a."FINANCIER_ID", o."ORG_NAME_AR", d."STAGE_CODE", s."NAME_AR"
