#!/usr/bin/env python3
"""
App 110's global page (page 0) carries its UI runtime in two static-content regions ("MFF UI Runtime", "MFF Iteration 4
UI"): a <style> block, the English -> Arabic dictionary and, per page, the layout of its form regions (layoutForm).
This writes them where the copied pages use them:
  web/public/apex/110/mff-ui.css            the region <style> blocks and page 0's inline CSS
  web/src/modules/mff/apex/mffUi.json       {"dict": {en: ar}, "layouts": {page: [[region static id, [[item, span], ...]], ...]}}

usage: apex_mff_ui.py <export app dir (p0000 inside)>
"""
import json
import os
import re
import sys


def main():
    p0 = os.path.join(sys.argv[1], 'p0000')
    root = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
    regions = [open(os.path.join(p0, 'regions', f), encoding='utf-8').read() for f in sorted(os.listdir(os.path.join(p0, 'regions')))]
    # the runtime (seq 999) runs before the Iteration 4 additions (seq 1000)
    regions.sort(key=lambda r: int(re.search(r'seq: (\d+)', r).group(1)))
    css, words, layouts = [], {}, {}
    for r in regions:
        css += re.findall(r'<style>(.*?)</style>', r, re.S)
        for script in re.findall(r'<script>(.*?)</script>', r, re.S):
            for m in re.finditer(r'var [DE]=(\{.*?\});', script, re.S):
                words.update(json.loads(m.group(1)))
            for m in re.finditer(r'p==="(\d+)"\)\{(.*?)\}(?:else|\n|;?\s*\};?$)', script, re.S):
                calls = re.findall(r'layoutForm\("([^"]+)",(\[\[.*?\]\])\)', m.group(2))
                layouts.setdefault(m.group(1), []).extend([rid, json.loads(cfg)] for rid, cfg in calls)
    page_css = os.path.join(p0, 'page.css')
    if os.path.exists(page_css):
        css.append(open(page_css, encoding='utf-8').read())
    out_css = os.path.join(root, 'web', 'public', 'apex', '110', 'mff-ui.css')
    with open(out_css, 'w', encoding='utf-8') as f:
        f.write('/* App 110 global page (page 0): the MFF UI Runtime styles and the page CSS. Generated by tools/oracle-port/apex_mff_ui.py. */\n')
        f.write('\n'.join(c.strip() for c in css) + '\n')
    out_json = os.path.join(root, 'web', 'src', 'modules', 'mff', 'apex', 'mffUi.json')
    with open(out_json, 'w', encoding='utf-8') as f:
        json.dump({'dict': words, 'layouts': layouts}, f, ensure_ascii=False, indent=1)
    print(out_css, len(css), 'style blocks;', out_json, len(words), 'words,', len(layouts), 'pages laid out')


if __name__ == '__main__':
    main()
